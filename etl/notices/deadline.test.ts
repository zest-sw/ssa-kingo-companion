import { describe, expect, it } from 'vitest';
import { deadlineOf, readDates, stripDates } from './deadline.ts';

// 본문 줄은 모두 직접 만든 조각이다(수집한 본문 문장을 옮기지 않는다). 제목은 공개 제목을 쓴다
describe('readDates', () => {
  it.each(['2026.04.20', '2026. 4. 20.', '04.20', '4/20', '2026년 4월 20일', "'26.4/20", '4/20월', 'Apr 20th, 2026'])(
    '%s → 2026-04-20', text => {
      expect(readDates(text, '2026-04-03')).toEqual(['2026-04-20']);
    }
  );

  it('요일이 붙은 기간과 끝에 일만 적은 기간을 읽는다', () => {
    expect(readDates('(11/9월~11/11수)', '2026-11-04')).toEqual(['2026-11-09', '2026-11-11']);
    expect(readDates('4/20(월)~24(금)', '2026-04-08')).toEqual(['2026-04-20', '2026-04-24']);
    expect(readDates('11월 1일 ~ 30일 18:00', '2026-10-30')).toEqual(['2026-11-01', '2026-11-30']);
    expect(readDates('9월 29(화)', '2026-09-20')).toEqual(['2026-09-29']);
  });

  it('끝 날이 시작 날보다 작으면 다음 달이다', () => {
    expect(readDates('4/28(화)~2(토)', '2026-04-20')).toEqual(['2026-04-28', '2026-05-02']);
    expect(readDates('12/28(월)~4(월)', '2026-12-20')).toEqual(['2026-12-28', '2027-01-04']);
  });

  it.each([
    '13:30 ~ 15:30', '10:00–17:00', '직전 학기 평점 3.0 이상', '2026-1학기', '1-2학년', '13/45', '2/30',
    'Llama 3.1', 'GPT-4.1', 'Python 3.12', 'v2.1', '학점 3.5 이상', '3.5점', '3.5%'
  ])('%s 는 날짜가 아니다', text => {
    expect(readDates(text, '2026-04-03')).toEqual([]);
  });

  it('영어 낱말 뒤라도 빗금 날짜는 읽고, 목록 번호는 뒤 날짜와 붙이지 않는다', () => {
    expect(readDates('SKKU AI Colloquium 11/20', '2026-11-01')).toEqual(['2026-11-20']);
    expect(readDates('1. 11월 15일까지', '2026-11-01')).toEqual(['2026-11-15']);
  });

  it('연도가 없는 날짜가 게시일보다 두 달 넘게 앞서면 다음 해다', () => {
    expect(readDates('1/5', '2026-12-20')).toEqual(['2027-01-05']);
    expect(readDates('3/9', '2026-04-01')).toEqual(['2026-03-09']);
  });

  it('게시 연도에 없는 2/29는 다음 해(윤년)로 본다', () => {
    expect(readDates('~2/29', '2027-12-15')).toEqual(['2028-02-29']);
  });
});

describe('stripDates', () => {
  it('날짜 표기만 다른 제목을 같게 만든다', () => {
    const a = stripDates('취업역량과 AI 활용역량을 한 번에! SSAFY 16기 모집 (~5/11)');
    expect(a).toBe('취업역량과 AI 활용역량을 한 번에! SSAFY 16기 모집');
    expect(stripDates('취업역량과 AI 활용역량을 한 번에! SSAFY 16기 모집 (~5/11월)')).toBe(a);
    expect(stripDates('[KB국민은행] 2026 하계 체험형 인턴 모집(IT부문) (~6/24)')).toBe('[KB국민은행] 2026 하계 체험형 인턴 모집(IT부문)');
  });
});

